-- =====================================================================
-- AJ Technologies: WhatsApp bot tables
-- Run this ONCE in Supabase: SQL Editor -> New query -> paste -> Run.
-- It is safe to run again (it only adds what is missing).
--
--   0. contact_enquiries   allows source/submitted_via = 'bot' (enquiries from the WhatsApp bot)
--   1. wa_contacts          one row per WhatsApp customer (name, language, opt-out, chat state)
--   2. wa_messages          every message in and out (customer, bot, admin)
--   3. wa_bookings          calls booked through the bot
--   4. wa_admin_alerts      alerts and reminders sent to AJ's WhatsApp
--   5. wa_broadcasts        offer broadcasts (template messages) + their recipients
--   6. updated_at triggers + Row Level Security (same as the other tables)
-- =====================================================================


-- ---------------------------------------------------------------------
-- 0. Enquiries from the bot: source = 'bot', submitted_via = 'bot'
-- ---------------------------------------------------------------------
ALTER TABLE public.contact_enquiries DROP CONSTRAINT IF EXISTS contact_enquiries_source_check;
ALTER TABLE public.contact_enquiries ADD CONSTRAINT contact_enquiries_source_check
    CHECK (source IN ('home', 'contact', 'bot'));

ALTER TABLE public.contact_enquiries DROP CONSTRAINT IF EXISTS contact_enquiries_submitted_via_check;
ALTER TABLE public.contact_enquiries ADD CONSTRAINT contact_enquiries_submitted_via_check
    CHECK (submitted_via IN ('form', 'whatsapp', 'bot'));


-- ---------------------------------------------------------------------
-- 1. WhatsApp contacts
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wa_contacts (
    wa_id                varchar(20)  PRIMARY KEY,                    -- digits only, e.g. 919876543210
    profile_name         varchar(120) NOT NULL DEFAULT '',            -- name on their WhatsApp profile
    name                 varchar(120) NOT NULL DEFAULT '',            -- name they told the bot
    business_name        varchar(160) NOT NULL DEFAULT '',
    email                varchar(254) NOT NULL DEFAULT '',
    language             varchar(12)  NOT NULL DEFAULT 'en',          -- en, ta, tanglish, hi, ml ...
    language_locked      boolean      NOT NULL DEFAULT false,         -- true = customer picked it in the menu
    opted_out            boolean      NOT NULL DEFAULT false,         -- sent STOP: no offer broadcasts
    opted_out_at         timestamptz,
    bot_enabled          boolean      NOT NULL DEFAULT true,          -- false = only you reply (dashboard)
    needs_reply          boolean      NOT NULL DEFAULT false,         -- asked for the team / bot is off
    unread_count         integer      NOT NULL DEFAULT 0 CHECK (unread_count >= 0),
    last_inbound_at      timestamptz,                                 -- last message FROM the customer
    last_outbound_at     timestamptz,
    last_message_at      timestamptz,
    last_message_preview varchar(200) NOT NULL DEFAULT '',
    state                jsonb        NOT NULL DEFAULT '{}'::jsonb,   -- where they are in a bot flow
    nudged_at            timestamptz,                                 -- last "continue?" reminder
    created_at           timestamptz  NOT NULL DEFAULT now(),
    updated_at           timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT wa_contacts_state_is_object CHECK (jsonb_typeof(state) = 'object')
);
CREATE INDEX IF NOT EXISTS wa_contacts_last_message_idx ON public.wa_contacts (last_message_at DESC NULLS LAST);


-- ---------------------------------------------------------------------
-- 2. WhatsApp messages
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wa_messages (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wa_id           varchar(20)  NOT NULL REFERENCES public.wa_contacts (wa_id) ON DELETE CASCADE,
    direction       varchar(3)   NOT NULL CHECK (direction IN ('in', 'out')),
    sender          varchar(10)  NOT NULL CHECK (sender IN ('customer', 'bot', 'admin', 'system')),
    msg_type        varchar(20)  NOT NULL DEFAULT 'text',             -- text, image, audio, document, interactive, template ...
    body            text         NOT NULL DEFAULT '',                 -- text (voice notes: the transcript)
    media_id        varchar(100) NOT NULL DEFAULT '',
    media_mime      varchar(100) NOT NULL DEFAULT '',
    media_filename  varchar(200) NOT NULL DEFAULT '',
    wamid           varchar(200) UNIQUE,                              -- WhatsApp message id (stops duplicates)
    status          varchar(12)  NOT NULL DEFAULT ''
                    CHECK (status IN ('', 'received', 'sent', 'delivered', 'read', 'failed')),
    error           text         NOT NULL DEFAULT '',
    created_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS wa_messages_chat_idx ON public.wa_messages (wa_id, id DESC);


-- ---------------------------------------------------------------------
-- 3. Call bookings
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wa_bookings (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wa_id         varchar(20)  REFERENCES public.wa_contacts (wa_id) ON DELETE SET NULL,
    name          varchar(120) NOT NULL DEFAULT '',
    phone         varchar(30)  NOT NULL DEFAULT '',
    topic         varchar(500) NOT NULL DEFAULT '',
    call_date     date         NOT NULL,                              -- India time
    call_time     time         NOT NULL,                              -- India time
    status        varchar(10)  NOT NULL DEFAULT 'booked'
                  CHECK (status IN ('booked', 'done', 'missed', 'cancelled')),
    enquiry_id    bigint       REFERENCES public.contact_enquiries (id) ON DELETE SET NULL,
    reminded_at   timestamptz,
    notes         text         NOT NULL DEFAULT '',                   -- private, dashboard only
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now()
);
-- one customer per time slot
CREATE UNIQUE INDEX IF NOT EXISTS wa_bookings_one_per_slot ON public.wa_bookings (call_date, call_time) WHERE status = 'booked';
CREATE INDEX IF NOT EXISTS wa_bookings_date_idx ON public.wa_bookings (call_date DESC, call_time DESC);


-- ---------------------------------------------------------------------
-- 4. Alerts and reminders for AJ
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wa_admin_alerts (
    id              bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind            varchar(20)  NOT NULL,                            -- new_enquiry, enquiry_reminder, call_booked ...
    ref_id          bigint,                                           -- enquiry / booking / review id
    wa_id           varchar(20)  NOT NULL DEFAULT '',
    summary         varchar(300) NOT NULL DEFAULT '',
    customer_name   varchar(120) NOT NULL DEFAULT '',
    customer_phone  varchar(30)  NOT NULL DEFAULT '',
    detail          text         NOT NULL DEFAULT '',
    due_at          timestamptz  NOT NULL DEFAULT now(),
    status          varchar(10)  NOT NULL DEFAULT 'pending'
                    CHECK (status IN ('pending', 'sending', 'sent', 'failed', 'skipped')),
    attempts        integer      NOT NULL DEFAULT 0,
    error           text         NOT NULL DEFAULT '',
    sent_at         timestamptz,
    created_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS wa_admin_alerts_due_idx ON public.wa_admin_alerts (status, due_at);


-- ---------------------------------------------------------------------
-- 5. Offer broadcasts
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.wa_broadcasts (
    id                 bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title              varchar(120) NOT NULL DEFAULT '',
    template_name      varchar(512) NOT NULL,
    template_language  varchar(15)  NOT NULL DEFAULT 'en',
    body_preview       text         NOT NULL DEFAULT '',
    params             jsonb        NOT NULL DEFAULT '[]'::jsonb,     -- ["{name}", "20% off"]
    header_image_url   varchar(500) NOT NULL DEFAULT '',
    status             varchar(10)  NOT NULL DEFAULT 'queued'
                       CHECK (status IN ('queued', 'sending', 'done', 'cancelled')),
    total              integer      NOT NULL DEFAULT 0,
    sent               integer      NOT NULL DEFAULT 0,
    failed             integer      NOT NULL DEFAULT 0,
    created_at         timestamptz  NOT NULL DEFAULT now(),
    started_at         timestamptz,
    finished_at        timestamptz,
    CONSTRAINT wa_broadcasts_params_is_array CHECK (jsonb_typeof(params) = 'array')
);

CREATE TABLE IF NOT EXISTS public.wa_broadcast_recipients (
    id            bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    broadcast_id  bigint       NOT NULL REFERENCES public.wa_broadcasts (id) ON DELETE CASCADE,
    wa_id         varchar(20)  NOT NULL,
    status        varchar(10)  NOT NULL DEFAULT 'queued'
                  CHECK (status IN ('queued', 'sending', 'sent', 'failed', 'skipped')),
    error         text         NOT NULL DEFAULT '',
    wamid         varchar(200) NOT NULL DEFAULT '',
    sent_at       timestamptz,
    CONSTRAINT wa_broadcast_recipients_once UNIQUE (broadcast_id, wa_id)
);
CREATE INDEX IF NOT EXISTS wa_broadcast_recipients_queue_idx ON public.wa_broadcast_recipients (status, broadcast_id);


-- ---------------------------------------------------------------------
-- 6. updated_at triggers (uses public.set_updated_at() from supabase_schema.sql)
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS wa_contacts_set_updated_at ON public.wa_contacts;
CREATE TRIGGER wa_contacts_set_updated_at
    BEFORE UPDATE ON public.wa_contacts
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

DROP TRIGGER IF EXISTS wa_bookings_set_updated_at ON public.wa_bookings;
CREATE TRIGGER wa_bookings_set_updated_at
    BEFORE UPDATE ON public.wa_bookings
    FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

